// The Gradle-side hook for the parity contract, deliberately thin.
//
// The comparison lives in `engine/LadderParityCheck.kt`: production code, no Android and no
// test framework in it. That way `android/tools/typecheck.sh` runs the exact same check on a
// plain JVM with kotlinc — no SDK, no emulator, no Gradle — and this file only supplies the
// fixture and the assertion style. A test that re-implemented the scoring here would be a
// second port to keep in sync, which is how a parity test ends up passing for the wrong
// reason while the phone disagrees with the server.
//
// Fixture: app/src/test/resources/parity/golden.json, generated by `npm run gen:golden` in
// engine/; engine's generated.test.js fails if the checked-in copy goes stale.
package ir.savak.client

import com.google.common.truth.Truth.assertThat
import ir.savak.client.engine.LadderParityCheck
import org.junit.Test
import java.io.File

class LadderParityTest {

    /**
     * Gradle puts unit-test resources on the classpath; `ParityMain.kt` (the kotlinc runner)
     * reads it by path. Both hand the same text to [LadderParityCheck], and that shared entry
     * point is the point: the CI test and the local check cannot drift apart.
     */
    private fun fixture(): String {
        val fromClasspath = javaClass.classLoader?.getResourceAsStream("parity/golden.json")
        val text = fromClasspath?.bufferedReader()?.use { it.readText() }
        if (text != null) return text
        val fallback = File("src/test/resources/parity/golden.json")
        check(fallback.isFile) { "parity fixture missing: neither the classpath nor ${fallback.path} has it" }
        return fallback.readText()
    }

    @Test
    fun `the kotlin scorer reproduces the engine row for row`() {
        val report = LadderParityCheck.check(fixture())
        assertThat(report.failures).isEmpty()
        assertThat(report.ok).isTrue()
    }

    @Test
    fun `the fixture is dense enough to pin the model`() {
        // Ten scenarios x the ladder: fewer rows means the generated fixture stopped covering
        // a rung, and a scorer that is only half-tested is untested where it matters.
        val report = LadderParityCheck.check(fixture())
        assertThat(report.scenarios).isAtLeast(8)
        assertThat(report.rows).isAtLeast(report.scenarios * 6)
    }

    @Test
    fun `a real divergence is reported instead of swallowed`() {
        assertThat(LadderParityCheck.checkDetectsMutation(fixture())).isTrue()
    }
}
