#!/usr/bin/env node
/**
 * Generates android/app/src/main/java/ir/savak/client/engine/LadderTable.kt from the
 * engine's RUNGS catalogue.
 *
 * Why generated instead of hand-ported: the phone re-implements the scoring function so
 * it can switch transports between check-ins. A hand-copied constants table drifts the
 * first time someone tunes a rung, and the failure mode is invisible — the app quietly
 * prefers a protocol the desktop engine would never have picked. One source of truth, and
 * test/ladder-table.test.js fails if the committed file is stale.
 *
 *   node tools/gen-kotlin-ladder.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import { RUNGS, allowedRungsFor, carrierOf } from '../src/ladder.js';
import { POLICIES } from '../src/tune.js';

const OUT = new URL('../../android/app/src/main/java/ir/savak/client/engine/LadderTable.kt', import.meta.url);
const check = process.argv.includes('--check');

const num = (v) => {
  if (v === null || v === undefined) return null;
  const n = Number(v);
  if (!Number.isFinite(n)) return null;
  return Number.isInteger(n) ? `${n}` : n.toFixed(6).replace(/0+$/, '').replace(/\.$/, '.0');
};
// Kotlin has no implicit Int→Double: `RungCost(rttCostMs = 1, …)` is a compile error.
// Everything typed as a Double in LadderTable.kt must therefore be emitted with a decimal
// point, or the generated file only fails at build time on somebody's laptop.
const dbl = (v, fallback = 0) => {
  const n = Number(v ?? fallback);
  if (!Number.isFinite(n)) return '0.0';
  return Number.isInteger(n) ? `${n}.0` : n.toFixed(6).replace(/0+$/, '').replace(/\.$/, '.0');
};

function affinityFields(a) {
  // Positional in the Kotlin data class: loss, shaping, udpQos, dpiQuic, dpiSni,
  // activeProbe, tcpOnly, cpu — names are explicit so a reordering cannot go unnoticed.
  const map = { loss: 'loss', shaping: 'shaping', udpQos: 'udp_qos', dpiQuic: 'dpi_quic', dpiSni: 'dpi_sni', activeProbe: 'active_probe', tcpOnly: 'tcp_only', cpu: 'cpu', cdn: 'cdn', ipBlocked: 'ip_blocked' };
  return Object.entries(map)
    .filter(([k]) => k !== 'cpu' || a?.cpu !== undefined)
    .map(([k, src]) => `${k} = ${dbl(a?.[src], 0)}`)
    .join(', ');
}

const rungLines = RUNGS.map((r) =>
  `    RungSpec(\n` +
  `        id = "${r.id}", title = ${ktString(r.title)}, family = Family.${r.family.toUpperCase().replace(/-/g, '_')},\n` +
  `        carrier = "${carrierOf(r.id)}", requiresUdp = ${!!r.requires?.udp}, requiresQuic = ${!!r.requires?.quic}, minMtu = ${num(r.requires?.mtuFloor) ?? 'null'},\n` +
  `        cost = RungCost(rttCostMs = ${dbl(r.cost?.rttCostMs)}, overheadPct = ${dbl(r.cost?.overheadPct)}, cpuLoad = ${dbl(r.cost?.cpuLoad)}),\n` +
  `        affinity = Affinity(${affinityFields(r.affinity)}),\n` +
  `        lineage = ${ktString(r.lineage)},\n` +
  `    ),`,
);

const WEIGHT_KEYS = ['throughput', 'latency', 'stability', 'evasion', 'cost'];

function ktString(s) {
  return `"${String(s ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

// Mode allowlists come from allowedRungsFor so the app cannot consider a rung the
// engine would never ship (legacy VMess is opt-in there too — allow it and let the
// caller decide, matching POLICIES.allowLegacy handling).
const policies = Object.entries(POLICIES)
  .map(([id]) => {
    // Default policy semantics, i.e. allowLegacy:false: the engine's planForNode() also
    // drops legacy VMess unless the operator opts in, so a table generated with
    // allowLegacy:true would hand the phone a rung the server never shipped. (Caught by
    // android/tools/typecheck.sh, which diffs the Kotlin order against the engine's.)
    const ids = allowedRungsFor(id, { allowLegacy: false }).map((r) => r.id);
    return `        "${id}" to setOf(${ids.map(ktString).join(', ')}),`;
  })
  .join('\n');

const weights = Object.entries(POLICIES)
  .map(([id, p]) => {
    const vals = WEIGHT_KEYS.map((k) => dbl(p.weights?.[k], 0));
    return `        "${id}" to doubleArrayOf(${vals.join(', ')}), // ${WEIGHT_KEYS.join('|')}`;
  })
  .join('\n');

const out =
  `// GENERATED by engine/tools/gen-kotlin-ladder.mjs — DO NOT EDIT.\n` +
  `//\n` +
  `// The device re-runs the ladder's scoring so it can switch transports between\n` +
  `// check-ins. Keeping the constants here generated from engine/src/ladder.js is what\n` +
  `// stops the phone and the CLI from disagreeing about which transport to prefer.\n` +
  `// Regenerate after changing a rung:  npm run gen:ladder\n` +
  `// (test/ladder-table.test.js fails the suite if this file is stale.)\n` +
  `package ir.savak.client.engine\n` +
  `\n` +
  `enum class Family { QUIC, TLS_TCP, RAW_UDP, RELAY }\n` +
  `\n` +
  `data class RungCost(val rttCostMs: Double, val overheadPct: Double, val cpuLoad: Double)\n` +
  `\n` +
  `/** How well a rung copes with each censor mechanism; 1.0 = unbothered. */\n` +
  `data class Affinity(\n` +
  `    val loss: Double,\n` +
  `    val shaping: Double,\n` +
  `    val udpQos: Double,\n` +
  `    val dpiQuic: Double,\n` +
  `    val dpiSni: Double,\n` +
  `    val activeProbe: Double,\n` +
  `    val tcpOnly: Double,\n` +
  `    val cpu: Double = 0.0,\n` +
  `    val cdn: Double = 0.0,\n` +
  `    val ipBlocked: Double = 0.0,\n` +
  `)\n` +
  `\n` +
  `data class RungSpec(\n` +
  `    val id: String,\n` +
  `    val title: String,\n` +
  `    val family: Family,\n` +
  `    val carrier: String,\n` +
  `    val requiresUdp: Boolean,\n` +
  `    val requiresQuic: Boolean,\n` +
  `    val minMtu: Int?,\n` +
  `    val cost: RungCost,\n` +
  `    val affinity: Affinity,\n` +
  `    val lineage: String,\n` +
  `)\n` +
  `\n` +
  `object LadderTable {\n` +
  `    val ALL: List<RungSpec> = listOf(\n${rungLines.map((l) => `    ${l.replace(/\n/g, '\n')}`).join('\n')}\n    )\n` +
  `\n` +
  `    val BY_ID: Map<String, RungSpec> = ALL.associateBy { it.id }\n` +
  `\n` +
  `    /** POLICIES in engine/src/tune.js — weights are throughput|latency|stability|evasion|cost. */\n` +
  `    val WEIGHTS: Map<String, DoubleArray> = mapOf(\n${weights}\n    )\n` +
  `\n` +
  `    val MODE_ALLOW: Map<String, Set<String>> = mapOf(\n${policies}\n    )\n` +
  `}\n`;

if (check) {
  let existing = null;
  try {
    existing = await readFile(OUT, 'utf8');
  } catch {
    /* missing */
  }
  if (existing !== out) {
    console.error('LadderTable.kt is STALE — run `npm run gen:ladder` and commit the result.');
    process.exitCode = 1;
  } else {
    console.log('LadderTable.kt is up to date');
  }
} else {
  await writeFile(OUT, out);
  console.log(`wrote ${RUNGS.length} rungs → android/.../engine/LadderTable.kt (${out.length} bytes)`);
}
